// py state.json -> SQL for D1 (DESIGN.md "Importer"):
//
//   node --experimental-strip-types scripts/import_state.ts state.json [--admin-dir DIR] > import.sql
//   npx wrangler d1 migrations apply duel-evolution --local|--remote
//   npx wrangler d1 execute duel-evolution --local|--remote --file import.sql
//
// The SQL first empties the state tables (re-running it replaces the state; auth tables are never touched), then
// inserts the rows of src/db/project.ts. With --admin-dir, py's admin files found there (admin_vetados.json,
// gm_cuentas.json, admin_tienda.json, admin_regalos.json) replace the admin tables too; other py files there are
// not imported.
// One statement per line, ≤ 100 rows / 90 KB each.
// accounts[acct].user_id is not imported (left NULL): legacy accounts are claimed later through de-auth. The keys of
// features this game does not have (project.ts RETIRED_KEYS) are stripped everywhere first.
// The importer checks the round trip before printing: it refuses a state it would not get back exactly.
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { adminRowsFromPy } from "../src/db/admin.ts";
import * as G from "../src/db/game-schema.ts";
import { RETIRED_KEYS, rowsToState, stateToRows, tableMeta } from "../src/db/project.ts";
import { clearStatements, insertStatements } from "../src/db/sql.ts";

type O = Record<string, any>;
const isObj = (x: unknown): x is O => typeof x === "object" && x !== null && !Array.isArray(x);

/** The state without RETIRED_KEYS, at the root (the owner's account), in every account, profile (archived ones
 *  too), record and wallet. Modifies st. */
export function stripRetired(st: O): O {
  const profile = (p: unknown) => {
    if (!isObj(p)) return;
    for (const k of RETIRED_KEYS.profile) delete p[k];
    if (isObj(p.rec)) for (const k of RETIRED_KEYS.rec) delete p.rec[k];
  };
  const account = (a: unknown) => {
    if (!isObj(a)) return;
    for (const k of RETIRED_KEYS.account) delete a[k];
    if (isObj(a.wallet)) for (const k of RETIRED_KEYS.wallet) delete a.wallet[k];
    if (isObj(a.profiles)) Object.values(a.profiles).forEach(profile);
    if (Array.isArray(a.profiles_borrados)) for (const e of a.profiles_borrados) if (isObj(e)) profile(e.perfil);
  };
  account(st);
  if (isObj(st.accounts)) Object.values(st.accounts).forEach(account);
  return st;
}

export function importSql(stateText: string, adminDir: string | null = null): string[] {
  const st = JSON.parse(stateText);
  if (typeof st !== "object" || st === null || Array.isArray(st)) throw new Error("state.json is not an object");
  stripRetired(st);
  for (const a of Object.values(st.accounts ?? {})) if (isObj(a)) delete a.user_id;
  const rows = stateToRows(st);
  if (JSON.stringify(rowsToState(JSON.parse(JSON.stringify(rows)))) !== JSON.stringify(st)) throw new Error("round trip mismatch: not importing");
  const out = [...clearStatements(), ...insertStatements(rows)];
  if (adminDir) {
    const read = (f: string) => (existsSync(join(adminDir, f)) ? JSON.parse(readFileSync(join(adminDir, f), "utf8")) : undefined);
    const tables = [G.adminBans, G.adminGm, G.adminFlags, G.shopPrices, G.adminStart].map(tableMeta);
    const ar = adminRowsFromPy({ bans: read("admin_vetados.json"), gm: read("gm_cuentas.json"), shop: read("admin_tienda.json"),
      start: read("admin_regalos.json") });
    out.push(...clearStatements(tables), ...insertStatements(ar, tables));
  }
  return out;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const args = process.argv.slice(2);
  const ai = args.indexOf("--admin-dir");
  const adminDir = ai >= 0 ? args.splice(ai, 2)[1] : null;
  if (args.length !== 1) {
    process.stderr.write("usage: node --experimental-strip-types scripts/import_state.ts state.json [--admin-dir DIR] > import.sql\n");
    process.exit(2);
  }
  const stmts = importSql(readFileSync(args[0], "utf8"), adminDir);
  process.stdout.write(`-- ${args[0]}: generated by scripts/import_state.ts\n${stmts.join("\n")}\n`);
  process.stderr.write(`${stmts.length} statements\n`);
}
