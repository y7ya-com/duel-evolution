import assert from 'node:assert/strict';
import { starterUniform } from '../controls/avatar-uniform.js';
import avatarRead from '../read/avatar.js';
const bytes = new DataView(new ArrayBuffer(0x10000)), w = 0x1000, back = 0x3000;
const u8 = a => bytes.getUint8(a), i32 = a => bytes.getInt32(a, true);
bytes.setUint32(w + 0x688 + 12 + 4, back, true);
bytes.setUint8(w + 0x738 + 6, 0x70);
const read = avatarRead({ u8, i32, ptr: a => bytes.getUint32(a + 4, true), shown: a => !!u8(a + 0xc4) }).windows.CWindowDialogAvatarSwitch;
assert.equal(read(w).avatarCreation, true);
assert.equal(read(w).avatarClothes, 0x70, 'CAvatarData bytes start after its vtable');
bytes.setUint8(w + 0x738, 1);
assert.equal(read(w).avatarSex, 1);
bytes.setUint8(back + 0xc4, 1);
assert.equal(read(w).avatarCreation, false, 'existing character dressing keeps its chosen outfit');
const calls = [], pending = [];
const api = { click: id => { calls.push(id); return new Promise(r => pending.push(r)); } };
const initial = { avatarCreation: true, avatarClothes: 0x70, avatarCategory: -1, avatarClothingButton: 99 };
const state = {};
starterUniform(initial, api, state);
const page = { ...initial, avatarCategory: 9, avatarItems: [{ id: 10, value: 0x70 }, { id: 11, value: 0x80 }] };
starterUniform(page, api, state);
assert.deepEqual(calls, [99], 'wait for the category click before selecting an item');
pending.shift()(); await new Promise(r => setImmediate(r));
assert.deepEqual(calls, [99, 11], 'select the Slifer part by value, independently of item order');
starterUniform({ ...page, avatarClothes: 0x80 }, api, state);
pending.shift()(); await new Promise(r => setImmediate(r));
assert.deepEqual(calls, [99, 11]);
starterUniform({ ...initial, avatarCreation: false }, api, state);
assert.deepEqual(calls, [99, 11]);
starterUniform({ ...page, avatarSex: 1 }, api, state);
assert.deepEqual(calls, [99, 11, 11], 'a body change reapplies the same Slifer clothing number');
pending.shift()(); await new Promise(r => setImmediate(r));
console.log('avatar creation uniform: ok');
