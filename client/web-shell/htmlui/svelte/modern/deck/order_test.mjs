import assert from 'node:assert/strict';
import { reconcileOrder, insertCopy, sortOrder } from './order.js';
assert.deepEqual(reconcileOrder([3, 1, 2, 1], [1, 1, 2, 3]), [3, 1, 2, 1]);
assert.deepEqual(reconcileOrder([3, 1, 2, 1], [1, 2, 3, 4]), [3, 1, 2, 4]);
assert.deepEqual(reconcileOrder([3, 1], [1, 1, 3]), [3, 1, 1]);
assert.deepEqual(insertCopy([3, 1, 2], 0, 3), [1, 2, 3]);
assert.deepEqual(insertCopy([3, 1, 2], 2, 0), [2, 3, 1]);
assert.deepEqual(insertCopy([1, 2, 1], 2, 1), [1, 1, 2]);
const cards = { 1: { name: 'B', atk: 200, level: 2 }, 2: { name: 'A', atk: 100, level: 4 } };
assert.deepEqual(sortOrder([1, 2], 'name', id => cards[id]), [2, 1]);
assert.deepEqual(sortOrder([1, 2], 'level', id => cards[id]), [2, 1]);
assert.deepEqual(sortOrder([1, 2], 'manual', id => cards[id]), [1, 2]);
console.log('order_test: ok');
