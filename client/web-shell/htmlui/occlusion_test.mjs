import assert from 'node:assert/strict';
import { clip, surfaceOrder, foregroundRects } from './occlusion.js';
const store = { id: 1, cls: 'CShopPackWindow', x: 264, y: 0, w: 760, h: 600 };
const ownedDialog = { id: 2, cls: 'CWindowModelDialogYesNo', shown: true, x: 350, y: 220, w: 320, h: 160 };
const nativePicker = { id: 3, cls: 'CWindowModelList', shown: true, x: 200, y: 620, w: 250, h: 70 };
const chat = { id: 4, cls: 'CChatWindow', shown: true, x: 12, y: 684, w: 414, h: 28 };
const windows = [ownedDialog, nativePicker, chat], all = { scene: 14, windows, tasks: [store] };
assert.deepEqual(surfaceOrder(all, x => x).map(s => s.id), [1, 2, 3, 4], 'HTML dialogs stay above the shop');
assert.deepEqual(surfaceOrder({ ...all, scene: 36 }, x => x).map(s => s.id), [2, 3, 4, 1], 'other scenes retain existing order');
const full = { x: 0, y: 0, w: 1024, h: 768 };
const front = foregroundRects(store, windows, new Set([1, 2, 4]), full, () => false);
assert.deepEqual(front, [nativePicker], 'an unowned picker cuts through even outside the old shop rectangle');
const mask = clip(front, full, store);
assert(mask.includes('M-264 0h1024v768h-1024z'), 'expanded surface clip uses the task root origin');
assert(mask.includes('M-64 620h250v70h-250z'), 'picker hole stays at its real game position');
assert.equal(clip([], full, store), '', 'no modal never crops the expanded shop');
assert.deepEqual(foregroundRects(store, [{ ...nativePicker, shown: false }], new Set(), full, () => true), []);
assert.deepEqual(foregroundRects(store, [{ ...nativePicker, drawn: null }], new Set(), full, () => true), [], 'undrawn dialogs do not cut holes');
const merged = clip([{ x: 10, y: 10, w: 30, h: 30 }, { x: 20, y: 20, w: 40, h: 40 }], full);
assert.equal((merged.match(/M/g) || []).length, 2, 'overlapping dialog holes cannot cancel under evenodd fill');
const ordinary = { id: 10, cls: 'CWindowModelDeck', x: 0, y: 0, w: 1024, h: 768 };
assert.deepEqual(foregroundRects(ordinary, windows, new Set(), full, other => other.id === 2), [ownedDialog]);
console.log('occlusion_test: ok');
