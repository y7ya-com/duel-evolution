import assert from 'node:assert/strict';
import { actionableCards } from './duel-actions.js';
const dv = new DataView(new ArrayBuffer(0x1300000));
const w = (p, v) => dv.setUint32(p, v, true);
const card = 0x4000, app = 0x1000, nd = 0x5000;
w(0x012711ac, app); w(app + 0xc70, nd); w(nd + 0x674, 1);
w(card, 0x00bebbc0); w(card + 4, 1); w(card + 0x14, 256);
w(card + 0x24, 11 << 1); w(card + 0x38, 500); w(card + 0x3c, 600); w(card + 0x44, 65536);
w(nd + 0x66a4 + 0x20, 3);
const h = { scene: 28, u8: p => dv.getUint8(p), u32: p => dv.getUint32(p, true), i32: p => dv.getInt32(p, true), vec: () => [0x3000] };
w(0x3000, card);
assert.equal(actionableCards(h).length, 1);
w(nd + 0x66a4 + 0x20, 1); assert.equal(actionableCards(h).length, 0, 'inspection alone is not a legal play');
w(nd + 0x66a4 + 0x20, 4); w(nd + 0x674, 0); assert.equal(actionableCards(h).length, 0, 'no stale highlights outside input');
w(nd + 0x674, 1); w(0x012a9084, 7); assert.equal(actionableCards(h).length, 0, 'spectators do not get move highlights');
w(0x012a9084, 0); w(card + 0x24, (11 << 1) | 1); assert.equal(actionableCards(h).length, 0, 'opponent hands stay private');
w(card + 0x24, 3 << 1); w(nd + 0x66a4 + 6, 8); assert.equal(actionableCards(h).length, 1, 'field permissions use the zone');
assert.deepEqual(actionableCards({ ...h, scene: 7 }), []);
console.log('duel-actions_test: ok');
