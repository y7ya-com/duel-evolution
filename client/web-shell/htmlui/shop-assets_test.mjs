import assert from 'node:assert/strict';
import { gzipSync } from 'node:zlib';
import { parseShopDirectory, shopAssetBytes } from './shop-assets.js';
const size = 10000;
const names = ['data/cardpack/pack.png', 'data/shop/category.png', 'data/common/text.png', 'data/avatar/clothes.png'];
const bytes = new Uint8Array(28 + names.length * 268), view = new DataView(bytes.buffer);
bytes.set(new TextEncoder().encode('YO2DIR1\0')); view.setBigUint64(8, BigInt(size), true);
bytes.set(new TextEncoder().encode('KCEJYUGI'), 16); view.setUint32(24, names.length, true);
names.forEach((name, i) => {
  const at = 28 + i * 268;
  [...name.replaceAll('/', '\\')].forEach((c, j) => { const n = c.charCodeAt(0); bytes[at + j] = (n & 15) << 4 | n >> 4; });
  view.setUint32(at + 256, 2000 + i * 100, true); view.setUint32(at + 260, 80, true); view.setUint32(at + 264, 40, true);
});
const entries = parseShopDirectory(bytes, size);
assert.deepEqual(entries.get(names[0]), [2000, 2040, 80]);
assert(entries.has(names[1])); assert(entries.has(names[3])); assert(!entries.has(names[2]));
assert.equal(parseShopDirectory(bytes, size + 1), null, 'stale sidecar cannot address another archive');
assert.equal(parseShopDirectory(bytes.subarray(0, bytes.length - 1), size), null);
let requests = 0;
const files2 = new Map(), art = new Uint8Array([1, 2, 3]);
const loader = { files: new Map([['game/merge.dat', { size }]]), files2, entry: async name => files2.has(name) ? art : null };
const fetcher = async url => { requests++; assert.equal(url, 'game/merge.dat.dir.gz'); return { status: 200, arrayBuffer: async () => gzipSync(bytes) }; };
assert.deepEqual(await shopAssetBytes(names[0], { loader, fetcher }), art);
assert.deepEqual(await shopAssetBytes(names[1], { loader, fetcher }), art);
assert.equal(requests, 1, 'one verified directory shared by all shop pictures');
assert.equal(await shopAssetBytes('data/common/text.png', { loader, fetcher }), null);
assert.equal(await shopAssetBytes('../secret', { loader, fetcher }), null);
view.setUint32(28 + 256, size + 100, true);
assert(!parseShopDirectory(bytes, size).has(names[0]), 'out-of-range entries are discarded');
console.log('shop-assets_test: ok');
