import assert from 'node:assert/strict';
import { applyNativeAppearance, setNativeAppearanceHeap, getNativeAppearanceHeap } from './native-appearance.js';
const heap = new Uint8Array(0x01300000), d = new DataView(heap.buffer), u32 = (p, n) => d.setUint32(p, n, true);
const app = 0x10000, account = 0x20000, data = 0x30000, game = 0x40000;
u32(0x012711ac, app); u32(app + 0xc68, account); u32(account, 0x00beb160);
u32(0x012714c4, data); u32(data, 0x00be5000); u32(0x012bb6b0, game); u32(game + 0x448, 0);
const me = account + 0x121c, slot = 2, player = me + 0x30 + slot * 0x1a8;
heap[me + 0x6d0] = slot; u32(player, 0x00be9d6c); heap[player + 4] = 1;
u32(player + 0x134, 0x01020304); u32(player + 0x148, 0x05060708);
const male = [0,0,32,48,64,96,119,144,176,32,0,0,0,1,2,3];
const female = [1,0,32,48,64,96,116,144,184,32,0,0,0,2,1,0];
const state = { world: 1, looks: { '0': male, '1': female } };
assert.equal(applyNativeAppearance(state, { HEAPU8: heap }), true);
assert.deepEqual([...heap.slice(player + 0x138, player + 0x148)], male);
assert.deepEqual([...heap.slice(player + 0x14c, player + 0x15c)], female);
assert.equal(d.getUint32(player + 0x134, true), 0x01020304, 'first avatar vtable untouched');
assert.equal(d.getUint32(player + 0x148, true), 0x05060708, 'second avatar vtable untouched');
assert.deepEqual([...heap.slice(data + 0xc8, data + 0xd8)], male, 'local PlayerData uses actual native world, not a response for the alternate look');
u32(game + 0x448, 1); applyNativeAppearance(state, { HEAPU8: heap });
assert.deepEqual([...heap.slice(data + 0xc8, data + 0xd8)], female, 'world changes copy the appropriate look into the transition cache');
const invalid = structuredClone(state); invalid.looks['1'][14] = 7;
const before = heap.slice(); assert.equal(applyNativeAppearance(invalid, { HEAPU8: heap }), false); assert.deepEqual(heap, before);
heap[me + 0x6d0] = 4;
const beforeSlot = heap.slice(); assert.equal(applyNativeAppearance(state, { HEAPU8: heap }), false); assert.deepEqual(heap, beforeSlot);
heap[me + 0x6d0] = slot; u32(account, 0);
assert.equal(applyNativeAppearance(state, { HEAPU8: heap }), false, 'unrecognized native object is never written');
assert.equal(applyNativeAppearance(state, { HEAPU8: new Uint8Array(100) }), false);
u32(account, 0x00beb160);
