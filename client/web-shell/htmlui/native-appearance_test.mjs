assert.equal(applyNativeAppearance(state, {}), true, 'a newly registered named active character works before PLAYERLIST sets valid');
setNativeAppearanceHeap(null);
assert.equal(applyNativeAppearance(state, {}), false, 'clearing the frame heap prevents stale heap access');
console.log('native appearance cache: both world looks, current-world PlayerData, vtable preservation and malformed-pointer refusal pass');
