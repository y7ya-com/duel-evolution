static const CNationFlag::Entry* findFlag(const vc6::string& code) {
    for (int i = 0; i < CNationFlag::kFlagCount; i++)
        if (std::strcmp(CNationFlag::kFlags[i].code, code.c_str()) == 0)
            return &CNationFlag::kFlags[i];
    return nullptr;
}

// @yo2 0x009d5a90 CNationFlag::create (new + task name + CTask::create)
