static int s_bad;
static bool check(const char* name, long args0, long args1, int mine, int ref) {
    if (mine == ref) return true;
    if (s_bad++ < 40) printf("bad %s %ld,%ld mine=%d ref=%d\n", name, args0, args1, mine, ref);
    return false;
}

int main(int argc, char** argv) {
    if (argc < 2 || !cardDbLoad(argv[1])) {
        fprintf(stderr, "no card data\n");
        return 2;
    }
    ref_init();
    static const int probes[] = {INT_MIN, -1000000, -70000, -4097, 0x10000, 70000, 1000000, INT_MAX};
    for (const Case& c : kCases) {
        long n = 0;
        int bad0 = s_bad;
        for (int rules : {-1, 0xc9}) {   // only engCard71c420 reads it
            g_rules = rules;
            for (int id = -4096; id < 0x10000; id++, n++) check(c.name, id, rules, c.mine(id), c.ref(id));
            for (int id : probes) n++, check(c.name, id, rules, c.mine(id), c.ref(id));
        }
        if (s_bad == bad0) printf("ok %s %ld\n", c.name, n);
    }
    g_rules = -1;
    long n = 0;
    for (int a = 0xe00; a < 0x2000; a++)
        for (int b = 0xe00; b < 0x2000; b++, n++) check("engSameCard", a, b, engSameCard(a, b), refw_717230(a, b));
    printf("ok engSameCard %ld\n", n);
    n = 0;
    for (int id = -16; id < 0x2000; id++)
        for (int g = 0; g < 0x48; g++, n++) check("engCardInGroup", id, g, engCardInGroup(id, g), refw_71a240(id, g));
    for (int g : {-1, -100, INT_MIN}) check("engCardInGroup", 0x1a77, g, engCardInGroup(0x1a77, g), 0);
    printf("ok engCardInGroup %ld\n", n);
    n = 0;
    for (int id = -4096; id < 0x10000; id++)
        for (int k = -3; k < 10; k++, n++) check("engChoiceText", id, k, engChoiceText(id, k), refw_71dbc0(id, k));
    printf("ok engChoiceText %ld\n", n);
    n = 0;
    for (int id = -4096; id < 0x10000; id++, n++) {
        int a[2] = {-7, -7}, b[2] = {-7, -7};
        int ra = engLvNext(id, a), rb = refw_719e50(id, b);
        check("engLvNext", id, 0, ra, rb);
        check("engLvNext.out0", id, 0, a[0], b[0]);
        check("engLvNext.out1", id, 0, a[1], b[1]);
        check("engLvNext.null", id, 0, engLvNext(id, nullptr), ra);
    }
    printf("ok engLvNext %ld\n", n);
    n = 0;
    for (int id = 0; id < 0x10000; id++) {
        uint16_t w[2] = {(uint16_t)id, 0};
        n++, check("engCard71ce20", id, 0, engCard71ce20(w), refw_71ce20(w));
        for (int loc = 0; loc < 0x100; loc++, n++) {
            w[1] = (uint16_t)(loc << 6 | (loc & 1) | 0xc000 * (loc >> 7));   // bits 6..13 all ways, a few others
            check("engCard71cbd0", id, w[1], engCard71cbd0(w), refw_71cbd0(w));
        }
    }
    printf("ok engCard71cbd0+engCard71ce20 %ld\n", n);
    // chain link records: every id with link words that cover each field the functions test
    for (int i = 0; i < 0x200; i++) DAT_012c8618[i] = (uint8_t)(i * 37 + 11);
    static const uint16_t w1s[] = {0, 1, 0x40, 0x41, 0x80, 0x940, 0x941, 0x1000, 0x1001, 0x1040, 0x2000, 0x2001,
                                   0x3000, 0x3001, 0x8000, 0x8001, 0x8940, 0x9001, 0xa040};
    static const uint16_t w3s[] = {0, 1, 2, 5, 6, 0x80};
    static const uint16_t tgts[] = {0x1c, 0x1d, 0x1e, 0x02, 0x3fe1};
    static const uint32_t dws[] = {0, 7, 8, 0x200, 0x207};
    n = 0;
    for (int id = 0; id < 0x2000; id++)
        for (uint16_t w1 : w1s)
            for (uint16_t w3 : w3s)
                for (int t = 0; t < 5; t++)
                    for (int w6 = 0; w6 < 4; w6++)
                        for (uint32_t dw : dws) {
                            uint16_t link[12] = {(uint16_t)id, w1, 0, w3, tgts[t], tgts[(t + 1) % 5], (uint16_t)w6,
                                                 tgts[(t + 2) % 5], tgts[(t + 3) % 5], (uint16_t)(id & 0x7f)};
                            memcpy(link + 10, &dw, 4);
                            n += 2;
                            check("engLinkSides", id, w1 << 16 | w3, (int)engLinkSides(link), refw_6eed70(link));
                            check("engLinkSpellSpeed", id, w1 << 16 | w6, engLinkSpellSpeed(link), refw_6ed310(link));
                        }
    printf("ok engLinkSides+engLinkSpellSpeed %ld\n", n);
    n = 0;
    for (int id = -4096; id < 0x10000; id++) {
        for (int k = -2; k < 0x22; k++, n += 2) {
            check("engCardAnswers", id, k, engCardAnswers(id, k), refw_6ed4a0(id, k));
            check("engCard6ee450", id, k, engCard6ee450(id, k), refw_6ee450(id, k));
        }
        if (id >= 0) {
            uint16_t w[2] = {(uint16_t)id, 0};
            n++, check("engLink6ee060", id, 0, engLink6ee060(w), refw_6ee060(w));
        }
    }
    int (*const empty[])() = {engNo6ee000, engNo6ee020, engNo6ee040, engNo6ee410, engNo6ee430};
    for (int i = 0; i < 5; i++, n++) check("engNo", i, 0, empty[i](), refw_6ee0x(i));
    printf("ok engCardAnswers+engCard6ee450+engLink6ee060+engNo %ld\n", n);
    // the sets for the archetype checks against the card list
    for (const Case& c : kCases) {
        printf("set %s", c.name);
        for (int id = 0xe00; id < 0x2000; id++)
            if (c.mine(id)) printf(" %d:%d", id, c.mine(id));
        printf("\n");
    }
    printf("bad total %d\n", s_bad);
    return s_bad ? 1 : 0;
}
