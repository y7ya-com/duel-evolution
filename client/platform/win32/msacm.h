// msacm32 for non-Windows. No codecs yet: acmStreamOpen and acmFormatSuggest fail, so yaneSDK plays PCM WAV and
// skips compressed (MP3/ADPCM) sounds, as on a PC without the codec. Decoders: DESIGN.md §7.
#pragma once
#include "mmreg.h"

DECLARE_HANDLE(HACMSTREAM);
DECLARE_HANDLE(HACMDRIVER);
typedef HACMSTREAM* LPHACMSTREAM;
#define ACMERR_NOTPOSSIBLE 512
#define ACM_STREAMOPENF_QUERY 0x00000001
#define ACM_STREAMOPENF_NONREALTIME 0x00000004
#define ACM_STREAMSIZEF_SOURCE 0x00000000L
#define ACM_STREAMSIZEF_DESTINATION 0x00000001L
#define ACM_STREAMCONVERTF_BLOCKALIGN 0x00000004
#define ACM_STREAMCONVERTF_START 0x00000010
#define ACM_STREAMCONVERTF_END 0x00000020
#define ACM_FORMATSUGGESTF_WFORMATTAG 0x00010000L
#define ACM_FORMATSUGGESTF_NCHANNELS 0x00020000L
#define ACM_FORMATSUGGESTF_NSAMPLESPERSEC 0x00040000L
#define ACM_FORMATSUGGESTF_WBITSPERSAMPLE 0x00080000L
typedef struct tACMSTREAMHEADER {
    DWORD cbStruct, fdwStatus;
    DWORD_PTR dwUser;
    LPBYTE pbSrc;
    DWORD cbSrcLength, cbSrcLengthUsed;
    DWORD_PTR dwSrcUser;
    LPBYTE pbDst;
    DWORD cbDstLength, cbDstLengthUsed;
    DWORD_PTR dwDstUser;
    DWORD dwReservedDriver[10];
} ACMSTREAMHEADER, *LPACMSTREAMHEADER;
MMRESULT acmStreamOpen(LPHACMSTREAM out, HACMDRIVER drv, LPWAVEFORMATEX src, LPWAVEFORMATEX dst, void* filter,
                       DWORD_PTR cb, DWORD_PTR inst, DWORD flags);
MMRESULT acmStreamClose(HACMSTREAM s, DWORD flags);
MMRESULT acmStreamSize(HACMSTREAM s, DWORD in, LPDWORD out, DWORD flags);
MMRESULT acmStreamPrepareHeader(HACMSTREAM s, LPACMSTREAMHEADER h, DWORD flags);
MMRESULT acmStreamUnprepareHeader(HACMSTREAM s, LPACMSTREAMHEADER h, DWORD flags);
MMRESULT acmStreamConvert(HACMSTREAM s, LPACMSTREAMHEADER h, DWORD flags);
MMRESULT acmFormatSuggest(HACMDRIVER drv, LPWAVEFORMATEX src, LPWAVEFORMATEX dst, DWORD size, DWORD flags);
