"""Writes the code page tables win32/text.cpp needs, from Python's own codecs (cp932 = Microsoft's Shift-JIS,
cp1252 = Windows Western). Run by CMake at configure time:

    python3 -I gen_codepages.py <out.inc>

cp932Lead[b] says whether b starts a double-byte character; cp932Single maps the single bytes; cp932Double maps
lead 0x81..0xFC x trail 0x40..0xFC (189 trails per lead) to UTF-16, 0 where the pair is undefined; cp1252 maps 0x80..0x9F
(the rest of cp1252 is Latin-1).  Self-test: python3 -I gen_codepages.py --test"""
import sys


def char(bs, codec):
    try:
        s = bs.decode(codec)
    except UnicodeDecodeError:
        return 0
    return ord(s) if len(s) == 1 and ord(s) < 0x10000 else 0


def tables():
    lead = [1 if 0x81 <= b <= 0x9F or 0xE0 <= b <= 0xFC else 0 for b in range(256)]
    single = [0 if lead[b] else char(bytes([b]), "cp932") for b in range(256)]
    double = [char(bytes([l, t]), "cp932") for l in range(0x81, 0xFD) for t in range(0x40, 0xFD)]
    w1252 = [char(bytes([b]), "cp1252") for b in range(0x80, 0xA0)]
    return lead, single, double, w1252


def emit(name, ctype, vals):
    rows = [", ".join(f"0x{v:x}" for v in vals[i:i + 16]) for i in range(0, len(vals), 16)]
    return f"static const {ctype} {name}[{len(vals)}] = {{\n    " + ",\n    ".join(rows) + "\n};\n"


if __name__ == "__main__":
    lead, single, double, w1252 = tables()
    if sys.argv[1:] == ["--test"]:
        assert double[(0x88 - 0x81) * 189 + (0x9f - 0x40)] == ord("亜")
        assert single[0xB1] == ord("ｱ") and single[0x5C] == 0x5C and w1252[0] == 0x20AC
        print("gen_codepages ok")
        sys.exit(0)
    with open(sys.argv[1], "w") as f:
        f.write("// generated by platform/tools/gen_codepages.py from Python's cp932 / cp1252 codecs\n")
        f.write(emit("cp932Lead", "unsigned char", lead) + emit("cp932Single", "unsigned short", single))
        f.write(emit("cp932Double", "unsigned short", double) + emit("cp1252High", "unsigned short", w1252))
